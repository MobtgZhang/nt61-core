/// read the `$DATA` stream of a record.
fn read_data_stream(
    reader: &dyn crate::SectorReader,
    ntfs: &NtfsBoot,
    record_num: u64,
) -> Option<Vec<u8>> {
    let record = read_mft_record(reader, ntfs, record_num)?;
    if &record[0..4] != b"FILE" {
        return None;
    }

    let mut off = u16::from_le_bytes([record[0x14], record[0x15]]) as usize;
    let end = ntfs.mft_record_size as usize;
    while off + 8 <= end {
        let attr_type = u32::from_le_bytes([
            record[off],
            record[off + 1],
            record[off + 2],
            record[off + 3],
        ]);
        if attr_type == 0xFFFFFFFF {
            break;
        }
        let attr_len = u32::from_le_bytes([
            record[off + 4],
            record[off + 5],
            record[off + 6],
            record[off + 7],
        ]) as usize;
        if attr_len == 0 || off + attr_len > end {
            break;
        }

        if attr_type == 0x80 {
            let non_resident = record[off + 8];
            if non_resident == 0 {
                // Resident $DATA: data is at off + value_offset.
                let value_offset =
                    u16::from_le_bytes([record[off + 0x14], record[off + 0x15]]) as usize;
                let content_size = u32::from_le_bytes([
                    record[off + 0x10],
                    record[off + 0x11],
                    record[off + 0x12],
                    record[off + 0x13],
                ]) as usize;
                if off + value_offset + content_size <= end {
                    return Some(
                        record[off + value_offset..off + value_offset + content_size].to_vec(),
                    );
                }
            } else {
                // Non-resident $DATA.  Real NTFS places the run-list
                // offset at +0x20, allocated size at +0x28, and real size
                // at +0x30.  Some boot images made by this project's
                // NTFS emitter move sizes forward by eight bytes, so fall
                // back to that layout when the standard run offset is not
                // a valid in-record run list.
                let standard_run_offset =
                    u16::from_le_bytes([record[off + 0x20], record[off + 0x21]]) as usize;
                let real_size = u64::from_le_bytes([
                    record[off + 0x30],
                    record[off + 0x31],
                    record[off + 0x32],
                    record[off + 0x33],
                    record[off + 0x34],
                    record[off + 0x35],
                    record[off + 0x36],
                    record[off + 0x37],
                ]);
                if standard_run_offset > 0 && standard_run_offset < end {
                    if let Some(data) = read_nonresident_runs(
                        reader,
                        ntfs,
                        &record,
                        off,
                        standard_run_offset,
                        off + attr_len,
                        real_size,
                    ) {
                        return Some(data);
                    }
                }

                let builder_real_size = u64::from_le_bytes([
                    record[off + 0x28],
                    record[off + 0x29],
                    record[off + 0x2A],
                    record[off + 0x2B],
                    record[off + 0x2C],
                    record[off + 0x2D],
                    record[off + 0x2E],
                    record[off + 0x2F],
                ]);
                let builder_run_offset =
                    u16::from_le_bytes([record[off + 0x38], record[off + 0x39]]) as usize;
                if builder_run_offset > 0 && builder_run_offset < end {
                    if let Some(data) = read_nonresident_runs(
                        reader,
                        ntfs,
                        &record,
                        off,
                        builder_run_offset,
                        off + attr_len,
                        builder_real_size,
                    ) {
                        return Some(data);
                    }
                }
            }
        }
        off += attr_len;
    }
    None
}

/// Parse a variable-length unsigned integer from a byte slice.
fn parse_varnum(bytes: &[u8], len: usize) -> u64 {
    let mut val = 0u64;
    for i in 0..len {
        val |= (bytes[i] as u64) << (i * 8);
    }
    val
}

/// Parse a variable-length signed integer from a byte slice (two's complement).
///
/// NTFS variable-length integers are little-endian, so the most
/// significant byte sits at `bytes[len - 1]`. Sign extension to a
/// full 64-bit `i64` only depends on the high bit of that byte —
/// not on whatever shifted bit position the previous version of
/// this code computed from `(8 - len)`. With that previous logic a
/// length-2 offset whose MSB happened to be 0 (e.g. `0x0021`) was
/// mis-sign-extended to a wild negative number (`-30859` in that
/// case), which made the MFT walker's `run_start_lcn` come back as
/// `0xffffffffffffffe8` and the read silently read the wrong
/// sectors. Use `(bytes[len - 1] & 0x80) != 0` to decide
/// sign-extension and pad the upper bytes with `0xFF` accordingly.
fn parse_varnum_signed(bytes: &[u8], len: usize) -> i64 {
    let mut val = 0i64;
    for i in 0..len {
        val |= (bytes[i] as i64) << (i * 8);
    }
    if len > 0 && (bytes[len - 1] & 0x80) != 0 {
        for i in len..8 {
            val |= 0xFFi64 << (i * 8);
        }
    }
    val
}

/// Parse all mapping pairs from an NTFS run list.  Returns
/// `(first_vcn, cluster_count, first_lcn)` triples.  Sparse runs have a
/// logical cluster number of zero and must be emitted as zeros.
fn parse_ntfs_runs(
    data: &[u8],
    run_offset: usize,
    run_end: usize,
) -> Option<alloc::vec::Vec<(u64, u64, u64)>> {
    let mut runs = alloc::vec::Vec::new();
    let mut rp = run_offset;
    let mut vcn = 0u64;
    while rp < run_end {
        if rp >= data.len() {
            return None;
        }
        let header = data[rp];
        if header == 0 || header == 0xFF {
            break;
        }
        let len_len = (header & 0x0F) as usize;
        let off_len = ((header >> 4) & 0x0F) as usize;
        if len_len == 0
            || len_len > 8
            || off_len > 8
            || rp + 1 + len_len + off_len > run_end
            || rp + 1 + len_len + off_len > data.len()
        {
            return None;
        }
        let mut len_bytes = [0u8; 8];
        for (index, byte) in data[rp + 1..rp + 1 + len_len].iter().enumerate() {
            len_bytes[index] = *byte;
        }
        let cluster_count = parse_varnum(&len_bytes, len_len);
        if cluster_count == 0 {
            return None;
        }
        let next_vcn = vcn.checked_add(cluster_count)?;
        let mut first_lcn = 0u64;
        if off_len > 0 {
            let mut offset_bytes = [0u8; 8];
            for (index, byte) in data[rp + 1 + len_len..rp + 1 + len_len + off_len]
                .iter()
                .enumerate()
            {
                offset_bytes[index] = *byte;
            }
            let delta = parse_varnum_signed(&offset_bytes, off_len);
            if delta < 0 {
                return None;
            }
            first_lcn = delta as u64;
        }
        runs.push((vcn, cluster_count, first_lcn));
        vcn = next_vcn;
        rp += 1 + len_len + off_len;
    }
    if runs.is_empty() {
        None
    } else {
        Some(runs)
    }
}

/// Read a non-resident attribute's runs into one byte vector.
fn read_nonresident_runs(
    reader: &dyn crate::SectorReader,
    ntfs: &NtfsBoot,
    data: &[u8],
    attr_off: usize,
    run_offset: usize,
    run_end: usize,
    real_size: u64,
) -> Option<alloc::vec::Vec<u8>> {
    const MAX_BOOT_FILE_SIZE: u64 = 256 * 1024 * 1024;
    if real_size == 0 || real_size > MAX_BOOT_FILE_SIZE {
        return None;
    }
    let runs = parse_ntfs_runs(data, attr_off + run_offset, run_end)?;
    let sectors_per_cluster = ntfs.sectors_per_cluster as u64;
    let mut out = alloc::vec![0u8; real_size as usize];
    let mut write_pos = 0usize;
    for (vcn, cluster_count, first_lcn) in runs {
        let start = (vcn.saturating_mul(sectors_per_cluster)).saturating_mul(512);
        if start > out.len() as u64 {
            return None;
        }
        write_pos = start as usize;
        let byte_count = cluster_count
            .saturating_mul(ntfs.sectors_per_cluster as u64)
            .saturating_mul(512);
        if first_lcn == 0 {
            write_pos = write_pos
                .saturating_add(byte_count.min(out.len() as u64 - write_pos as u64) as usize);
            continue;
        }
        let sector_count = cluster_count.saturating_mul(sectors_per_cluster);
        let sector_count = u32::try_from(sector_count).ok()?;
        let bytes = reader.read_sectors(
            first_lcn.saturating_mul(sectors_per_cluster),
            sector_count,
        )?;
        let take = byte_count.min(out.len() as u64 - write_pos as u64) as usize;
        if take == 0 {
            break;
        }
        if take > bytes.len() {
            return None;
        }
        out[write_pos..write_pos + take as usize].copy_from_slice(&bytes[..take as usize]);
        write_pos += take as usize;
        if write_pos == out.len() {
            break;
        }
    }
    if write_pos != out.len() {
        return None;
    }
    Some(out)
}

