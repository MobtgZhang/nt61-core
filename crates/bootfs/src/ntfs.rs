//! NTFS boot reader shared by firmware loaders and host image validation.

use alloc::vec::Vec;

/// Minimal NTFS boot-sector data we need for MFT traversal.
/// (Same struct as in boot/src/main.rs.)
struct NtfsBoot {
    sectors_per_cluster: u8,
    mft_start_lcn: u64,
    mft_record_size: u32,
    index_record_size: u32,
}

impl NtfsBoot {
    /// Parse the NTFS boot sector (first 512 bytes of the partition).
    fn parse(buf: &[u8; 512]) -> Option<Self> {
        if &buf[3..11] != b"NTFS    " {
            return None;
        }
        let bytes_per_sector = u16::from_le_bytes([buf[0x0B], buf[0x0C]]);
        let sectors_per_cluster = buf[0x0D];
        let mft_start_lcn = u64::from_le_bytes([
            buf[0x30], buf[0x31], buf[0x32], buf[0x33], buf[0x34], buf[0x35], buf[0x36], buf[0x37],
        ]);
        // MFT record size: byte 0x40 holds a signed value.
        // Positive = val clusters. Negative = 2^|val| bytes.
        let mft_raw = buf[0x40] as i8;
        let mft_record_size: u32 = if mft_raw >= 0 {
            let cluster_bytes =
                (sectors_per_cluster as u32).checked_mul(bytes_per_sector as u32)?;
            cluster_bytes.checked_mul(mft_raw as u32)?
        } else {
            1u32.checked_shl(-mft_raw as u32)?
        };
        if bytes_per_sector != 512 || !sectors_per_cluster.is_power_of_two() {
            return None;
        }
        if mft_record_size < 1024 || mft_record_size > 64 * 1024 {
            return None;
        }
        let index_raw = buf[0x44] as i8;
        let index_record_size = if index_raw > 0 {
            (index_raw as u32).checked_mul(sectors_per_cluster as u32 * bytes_per_sector as u32)?
        } else {
            1u32.checked_shl(-(index_raw as i32) as u32)?
        };
        if index_record_size < 512 || index_record_size > 64 * 1024 {
            return None;
        }
        Some(NtfsBoot {
            sectors_per_cluster,
            mft_start_lcn,
            mft_record_size,
            index_record_size,
        })
    }
}

/// read a single MFT record into a fresh buffer.
fn read_mft_record(
    reader: &dyn crate::SectorReader,
    ntfs: &NtfsBoot,
    record_num: u64,
) -> Option<Vec<u8>> {
    let sectors_per_record = ((ntfs.mft_record_size + 511) / 512) as u32;
    let lba = ntfs.mft_start_lcn * (ntfs.sectors_per_cluster as u64)
        + record_num * (ntfs.mft_record_size as u64) / 512;
    let mut buf = reader.read_sectors(lba, sectors_per_record)?;
    if buf.len() < ntfs.mft_record_size as usize {
        return None;
    }
    if !apply_mft_fixup(&mut buf) {
        return None;
    }
    Some(buf)
}

/// Apply the NTFS multi-sector transfer fixup array to an MFT record.
///
/// The array layout is authoritative in the kernel driver:
/// the first `u16` at `fixup_offset` is the update sequence number,
/// and each saved sector tail follows it.
fn apply_mft_fixup(record: &mut [u8]) -> bool {
    if record.len() < 512 {
        return false;
    }

    let fixup_offset = u16::from_le_bytes([record[4], record[5]]) as usize;
    let fixup_size = u16::from_le_bytes([record[6], record[7]]) as usize;

    if fixup_size == 0 || fixup_offset < 8 || fixup_offset >= record.len() {
        return false;
    }

    let fixup_count = fixup_size - 1;
    if fixup_count != record.len() / 512 || fixup_offset + 2 + fixup_count * 2 > record.len() {
        return false;
    }

    let usn = u16::from_le_bytes([record[fixup_offset], record[fixup_offset + 1]]);

    for sector_index in 0..fixup_count {
        let fixup_entry_offset = fixup_offset + 2 + sector_index * 2;
        let sector_tail_offset = ((sector_index + 1) * 512) - 2;

        if fixup_entry_offset + 2 > record.len() || sector_tail_offset + 2 > record.len() {
            return false;
        }

        let current =
            u16::from_le_bytes([record[sector_tail_offset], record[sector_tail_offset + 1]]);
        if current != usn {
            return false;
        }

        let saved_tail = [record[fixup_entry_offset], record[fixup_entry_offset + 1]];
        record[sector_tail_offset..sector_tail_offset + 2].copy_from_slice(&saved_tail);
    }

    true
}

/// Apply the fixup array to an index-allocation buffer.  Unlike MFT
/// records, boot images generated by the in-tree builder may omit the
/// fixup array entirely, so malformed metadata is left unchanged rather
/// than failing the whole directory lookup.
fn apply_indx_fixup_if_present(buffer: &mut [u8]) -> bool {
    if buffer.len() < 512 {
        return false;
    }
    let fixup_offset = u16::from_le_bytes([buffer[4], buffer[5]]) as usize;
    let fixup_size = u16::from_le_bytes([buffer[6], buffer[7]]) as usize;
    if fixup_size == 0 || fixup_offset < 8 || fixup_offset >= buffer.len() {
        return true;
    }
    let fixup_count = fixup_size.saturating_sub(1);
    if fixup_count != buffer.len() / 512
        || fixup_offset.saturating_add(2 + fixup_count.saturating_mul(2)) > buffer.len()
    {
        return true;
    }
    apply_mft_fixup(buffer)
}

