/// Read a volume-relative path using 512-byte sectors.
pub fn read_file(reader: &dyn crate::SectorReader, path: &str) -> Option<Vec<u8>> {
    let sector = reader.read_sectors(0, 1)?;
    let ntfs = NtfsBoot::parse(sector.as_slice().try_into().ok()?)?;
    let record = resolve_mft_record(reader, &ntfs, path)?;
    read_data_stream(reader, &ntfs, record)
}

#[cfg(test)]
mod tests {
    use super::*;

    struct Volume(Vec<u8>);
    impl crate::SectorReader for Volume {
        fn read_sectors(&self, lba: u64, count: u32) -> Option<Vec<u8>> {
            let start = usize::try_from(lba.checked_mul(512)?).ok()?;
            Some(self.0.get(start..start.checked_add(count as usize * 512)?)?.to_vec())
        }
    }
    fn put16(b: &mut [u8], off: usize, v: u16) { b[off..off+2].copy_from_slice(&v.to_le_bytes()); }
    fn put32(b: &mut [u8], off: usize, v: u32) { b[off..off+4].copy_from_slice(&v.to_le_bytes()); }
    fn put64(b: &mut [u8], off: usize, v: u64) { b[off..off+8].copy_from_slice(&v.to_le_bytes()); }
    fn protect(record: &mut [u8]) {
        let off = u16::from_le_bytes(record[4..6].try_into().unwrap()) as usize;
        put16(record, 6, (record.len() / 512 + 1) as u16);
        put16(record, off, 0xabcd);
        for sector in 0..record.len()/512 {
            let tail = (sector+1)*512-2;
            let original = u16::from_le_bytes(record[tail..tail+2].try_into().unwrap());
            put16(record, off+2+sector*2, original);
            put16(record, tail, 0xabcd);
        }
    }

    #[test]
    fn reads_4k_index_nodes_with_1k_mft_records() {
        let mut volume = Volume(vec![0; 33*4096]);
        let boot = &mut volume.0[..512];
        boot[3..11].copy_from_slice(b"NTFS    ");
        put16(boot, 11, 512);
        boot[13] = 8;
        put64(boot, 0x30, 1);
        boot[0x40] = (-10i8) as u8;
        boot[0x44] = (-12i8) as u8;
        // Root directory's nonresident INDEX_ALLOCATION is one 4 KiB cluster.
        let root = &mut volume.0[4096+5*1024..4096+6*1024];
        root[..4].copy_from_slice(b"FILE");
        put16(root, 4, 48);
        put16(root, 20, 56);
        put32(root, 56, 0xa0);
        put32(root, 60, 72);
        root[64] = 1;
        put16(root, 56+0x20, 64);
        put64(root, 56+0x28, 4096);
        root[120..124].copy_from_slice(&[0x11, 1, 32, 0]);
        put32(root, 128, 0xffffffff);
        protect(root);
        let file = &mut volume.0[4096+16*1024..4096+17*1024];
        file[..4].copy_from_slice(b"FILE");
        put16(file, 4, 48);
        put16(file, 20, 56);
        put32(file, 56, 0x80);
        put32(file, 60, 32);
        put32(file, 72, 7);
        put16(file, 76, 24);
        file[80..87].copy_from_slice(b"payload");
        put32(file, 88, 0xffffffff);
        protect(file);
        let node = &mut volume.0[32*4096..33*4096];
        node[..4].copy_from_slice(b"INDX");
        put16(node, 4, 40);
        // The valid key lies beyond the first MFT-sized slice.
        put32(node, 24, 2048-24);
        put32(node, 28, 2048+104+16-24);
        put64(node, 2048, 16);
        put16(node, 2056, 104);
        put16(node, 2058, 82);
        node[2048+16+64] = 8;
        for (i, c) in "last.exe".encode_utf16().enumerate() {
            put16(node, 2048+16+66+i*2, c);
        }
        put16(node, 2048+104+8, 16);
        put16(node, 2048+104+12, 2);
        protect(node);
        assert_eq!(read_file(&volume, "/last.exe"), Some(b"payload".to_vec()));
    }
}
