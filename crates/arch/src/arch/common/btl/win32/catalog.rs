pub fn resolve(id: u32) -> Option<&'static Api> {
    APIS.iter().find(|api| api.id == id)
}
pub fn find(dll: &str, name: &str) -> Option<&'static Api> {
    APIS.iter()
        .find(|api| api.dll.eq_ignore_ascii_case(dll) && api.name == name)
}

/// Runtime availability is independent of linkable ABI metadata. New exports
/// remain unsupported until explicitly classified against win32::dispatch,
/// win32::invoke or win32::nt_service; a name in APIS is never implementation.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum SupportStatus {
    ImplementedLimited,
    HostService,
    Unsupported,
}
impl SupportStatus {
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::ImplementedLimited => "implemented_limited",
            Self::HostService => "host_service",
            Self::Unsupported => "unsupported",
        }
    }
}
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct RuntimeSupport {
    pub status: SupportStatus,
    pub scope: &'static str,
}

