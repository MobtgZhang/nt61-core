//! Checked native lowering for register-only guest instructions.

use super::{DecodeMode, GuestState, IROp, IrInst, X86Reg};
use crate::arch::common::btl::{exec::set_alu_flags, ir::{AluOp, ByteOperand}};
use alloc::{boxed::Box, vec::Vec};

#[cfg(target_arch = "x86_64")]
pub type Entry = unsafe extern "sysv64" fn(*mut u64, u64);
#[cfg(not(target_arch = "x86_64"))]
pub type Entry = unsafe extern "C" fn(*mut u64, u64);

/// # Safety
/// The entry must remain executable and immutable until this object is dropped.
/// It must contain exactly the code accepted by the publisher.
pub unsafe trait Executable {
    fn entry(&self) -> Entry;
}

/// # Safety
/// A successful publication must return an entry bound to the exact bytes
/// supplied to this call, with the host ABI and instruction-fetch coherence.
/// The mapping must remain executable and immutable for the object's lifetime.
pub unsafe trait Publisher {
    /// Publish compiler-generated bytes with host instruction-fetch coherence.
    fn publish(&mut self, code: &[u8]) -> Option<Box<dyn Executable>>;
}

#[derive(Clone, Copy, PartialEq, Eq)]
struct RegisterOp {
    destination: X86Reg,
    source: Option<X86Reg>,
    width: u8,
    complement: bool,
    alu: Option<AluOp>,
}

pub struct Jit<'a> {
    publisher: &'a mut dyn Publisher,
    cache: Vec<(RegisterOp, Box<dyn Executable>)>,
    retired: u64,
}

impl<'a> Jit<'a> {
    pub fn new(publisher: &'a mut dyn Publisher) -> Self {
        Self { publisher, cache: Vec::new(), retired: 0 }
    }

    pub fn retired(&self) -> u64 {
        self.retired
    }

    pub(super) fn try_execute(&mut self, instruction: IrInst, state: &mut GuestState) -> bool {
        if state.rip != instruction.guest_va || !(1..=15).contains(&instruction.guest_len) {
            return false;
        }
        let width = instruction.operand_width;
        if !matches!(width, 1 | 2 | 4) && !(width == 8 && state.mode == DecodeMode::X64) {
            return false;
        }
        let (destination, source, immediate, complement, source_shift, destination_shift, alu) = match instruction.op {
            IROp::MovImm { dst, imm } if width != 1 => (dst, None, imm as u64, false, 0, 0, None),
            IROp::MovReg { dst, src } if width != 1 => (dst, Some(src), 0, false, 0, 0, None),
            IROp::ByteImmediate { dst: ByteOperand::Register { reg, high_byte }, value }
                if width == 1 => (reg, None, u64::from(value), false, 0, u32::from(high_byte) * 8, None),
            IROp::ByteMove {
                dst: ByteOperand::Register { reg: dst, high_byte: dst_high },
                src: ByteOperand::Register { reg: src, high_byte: src_high },
            } if width == 1 => (dst, Some(src), 0, false, u32::from(src_high) * 8, u32::from(dst_high) * 8, None),
            IROp::UnaryNotNeg { dst: Ok(dst), high_byte, negate: false }
                if !high_byte || width == 1 => {
                    let shift = u32::from(high_byte) * 8;
                    (dst, Some(dst), 0, true, shift, shift, None)
                }
            IROp::AluReg { op, dst, src } if width != 1 && !matches!(op, AluOp::Adc | AluOp::Sbb) =>
                (dst, Some(src), 0, false, 0, 0, Some(op)),
            IROp::AluImm { op, dst, imm } if width != 1 && !matches!(op, AluOp::Adc | AluOp::Sbb) =>
                (dst, None, imm as u64, false, 0, 0, Some(op)),
            IROp::ByteAlu {
                op,
                dst: ByteOperand::Register { reg: dst, high_byte: dst_high },
                src: ByteOperand::Register { reg: src, high_byte: src_high },
            } if width == 1 && !matches!(op, AluOp::Adc | AluOp::Sbb) => {
                let operand = (state.reg(src) >> (u32::from(src_high) * 8)) & 0xff;
                (dst, None, operand, false, 0, u32::from(dst_high) * 8, Some(op))
            }
            IROp::ByteAluImmediate {
                op,
                dst: ByteOperand::Register { reg, high_byte },
                immediate,
            } if width == 1 && !matches!(op, AluOp::Adc | AluOp::Sbb) =>
                (reg, None, u64::from(immediate), false, 0, u32::from(high_byte) * 8, Some(op)),
            _ => return false,
        };
        if destination == X86Reg::Rip || source == Some(X86Reg::Rip) {
            return false;
        }
        let native_alu = match alu {
            Some(AluOp::Cmp) => Some(AluOp::Sub),
            Some(AluOp::Test) => Some(AluOp::And),
            other => other,
        };
        let operation = RegisterOp { destination, source, width: width.max(4), complement, alu: native_alu };
        let entry = if let Some((_, code)) = self.cache.iter().find(|(key, _)| *key == operation) {
            code.entry()
        } else {
            if self.cache.len() >= 64 || self.cache.try_reserve(1).is_err() {
                return false;
            }
            let bytes = encode(operation);
            if bytes.is_empty() { return false; }
            let Some(code) = self.publisher.publish(&bytes) else { return false; };
            let entry = code.entry();
            self.cache.push((operation, code));
            entry
        };
        let value = if width <= 4 { u64::from(immediate as u32) } else { immediate };
        let previous = state.reg(destination);
        let operand = source.map_or(value, |register| state.reg(register));
        let left = previous >> destination_shift;
        if width == 1 && alu.is_some() {
            state.set_reg(destination, left & 0xff);
        }
        unsafe { entry(state.regs.as_mut_ptr(), value) };
        if let Some(op) = alu {
            let mask = u64::MAX >> (64 - u32::from(width) * 8);
            let result = state.reg(destination) & mask;
            set_alu_flags(state, op, left & mask, operand & mask, result, width);
            let stored = if matches!(op, AluOp::Cmp | AluOp::Test) {
                previous
            } else if width < 4 {
                (previous & !(mask << destination_shift)) | (result << destination_shift)
            } else {
                result
            };
            state.set_reg(destination, stored);
        } else if width < 4 {
            let mask = if width == 1 { 0xff } else { 0xffff };
            let field = (state.reg(destination) >> source_shift) & mask;
            state.set_reg(destination, (previous & !(mask << destination_shift)) | (field << destination_shift));
        } else if width == 4 && complement {
            state.set_reg(destination, u64::from(state.reg(destination) as u32));
        }
        state.set_reg(X86Reg::Rip, instruction.guest_va.wrapping_add(u64::from(instruction.guest_len)));
        self.retired = self.retired.saturating_add(1);
        true
    }
}

#[cfg(target_arch = "x86_64")]
fn encode(operation: RegisterOp) -> Vec<u8> {
    let mut bytes = Vec::with_capacity(18);
    if let Some(op) = operation.alu {
        bytes.extend_from_slice(&[0x48, 0x8b, 0x47, operation.destination as u8 * 8]);
        if let Some(source) = operation.source {
            bytes.extend_from_slice(&[0x48, 0x8b, 0x77, source as u8 * 8]);
        }
        let opcode = match op {
            AluOp::Add => 0x01,
            AluOp::Sub => 0x29,
            AluOp::And => 0x21,
            AluOp::Or => 0x09,
            AluOp::Xor => 0x31,
            _ => return Vec::new(),
        };
        bytes.extend_from_slice(&[0x48, opcode, 0xf0, 0x48, 0x89, 0x47, operation.destination as u8 * 8, 0xc3]);
        return bytes;
    }
    let source = if let Some(source) = operation.source {
        if operation.width == 8 { bytes.push(0x48); }
        bytes.extend_from_slice(&[0x8b, 0x47, source as u8 * 8]);
        if operation.complement { bytes.extend_from_slice(&[0x48, 0xf7, 0xd0]); }
        0x47
    } else {
        0x77
    };
    bytes.extend_from_slice(&[0x48, 0x89, source, operation.destination as u8 * 8, 0xc3]);
    bytes
}

#[cfg(target_arch = "aarch64")]
fn encode(operation: RegisterOp) -> Vec<u8> {
    let mut words = Vec::<u32>::with_capacity(4);
    if let Some(source) = operation.source {
        let base = if operation.width == 8 { 0xf940_0000 } else { 0xb940_0000 };
        let offset = u32::from(source as u8) * (8 / u32::from(operation.width));
        words.push(base | (offset << 10) | 1);
    }
    if operation.complement { words.push(0xaa21_03e1); }
    if let Some(op) = operation.alu {
        let opcode = match op {
            AluOp::Add => 0x8b01_0041,
            AluOp::Sub => 0xcb01_0041,
            AluOp::And => 0x8a01_0041,
            AluOp::Or => 0xaa01_0041,
            AluOp::Xor => 0xca01_0041,
            _ => return Vec::new(),
        };
        words.push(0xf940_0002 | (u32::from(operation.destination as u8) << 10));
        words.push(opcode);
    }
    words.push(0xf900_0001 | (u32::from(operation.destination as u8) << 10));
    words.push(0xd65f_03c0);
    words.into_iter().flat_map(u32::to_le_bytes).collect()
}

#[cfg(target_arch = "riscv64")]
fn encode(operation: RegisterOp) -> Vec<u8> {
    let mut words = Vec::<u32>::with_capacity(4);
    if let Some(source) = operation.source {
        let function = if operation.width == 8 { 3 } else { 6 };
        words.push((u32::from(source as u8) * 8 << 20) | (10 << 15) | (function << 12) | (11 << 7) | 3);
    }
    if operation.complement { words.push(0xfff5_c593); }
    if let Some(op) = operation.alu {
        let function = match op {
            AluOp::Add => 0,
            AluOp::Sub => 1 << 30,
            AluOp::And => 7 << 12,
            AluOp::Or => 6 << 12,
            AluOp::Xor => 4 << 12,
            _ => return Vec::new(),
        };
        words.push((u32::from(operation.destination as u8) * 8 << 20) | (10 << 15) | (3 << 12) | (12 << 7) | 3);
        words.push(function | (11 << 20) | (12 << 15) | (11 << 7) | 0x33);
    }
    let offset = u32::from(operation.destination as u8) * 8;
    words.push(((offset >> 5) << 25) | (11 << 20) | (10 << 15) | (3 << 12) | ((offset & 31) << 7) | 0x23);
    words.push(0x0000_8067);
    words.into_iter().flat_map(u32::to_le_bytes).collect()
}

#[cfg(target_arch = "loongarch64")]
fn encode(operation: RegisterOp) -> Vec<u8> {
    let mut words = Vec::<u32>::with_capacity(4);
    if let Some(source) = operation.source {
        let base = if operation.width == 8 { 0x28c0_0000 } else { 0x2a80_0000 };
        words.push(base | (u32::from(source as u8) * 8 << 10) | (4 << 5) | 5);
    }
    if operation.complement { words.push(0x0014_00a5); }
    if let Some(op) = operation.alu {
        let opcode = match op {
            AluOp::Add => 0x0010_8000,
            AluOp::Sub => 0x0011_8000,
            AluOp::And => 0x0014_8000,
            AluOp::Or => 0x0015_0000,
            AluOp::Xor => 0x0015_8000,
            _ => return Vec::new(),
        };
        words.push(0x28c0_0000 | (u32::from(operation.destination as u8) * 8 << 10) | (4 << 5) | 6);
        words.push(opcode | (5 << 10) | (6 << 5) | 5);
    }
    words.push(0x29c0_0000 | (u32::from(operation.destination as u8) * 8 << 10) | (4 << 5) | 5);
    words.push(0x4c00_0020);
    words.into_iter().flat_map(u32::to_le_bytes).collect()
}

#[cfg(not(any(target_arch = "x86_64", target_arch = "aarch64", target_arch = "riscv64", target_arch = "loongarch64")))]
fn encode(_: RegisterOp) -> Vec<u8> {
    Vec::new()
}
