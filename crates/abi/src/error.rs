/// `NT_SUCCESS` predicate: a status is successful when the high bit
/// is clear.
#[inline]
pub const fn nt_success(status: i64) -> bool {
    (status as u64 as u32 as i32) >= 0
}

/// Convert an `NTSTATUS` into the Win32 error code that
/// `GetLastError` should report.
pub const fn ntstatus_to_win32(status: i64) -> DWORD {
    match status as u32 {
        0x0000_0000 => ERROR_SUCCESS,
        0xC000_0001 => ERROR_INVALID_FUNCTION,
        0xC000_0002 => ERROR_CALL_NOT_IMPLEMENTED,
        0xC000_0003 => ERROR_INVALID_PARAMETER,
        0xC000_0008 => ERROR_INVALID_HANDLE,
        0xC000_000D => ERROR_INVALID_PARAMETER,
        0xC000_000F => ERROR_FILE_NOT_FOUND,
        0xC000_0010 => ERROR_INVALID_FUNCTION,
        0xC000_0011 => ERROR_HANDLE_EOF,
        0xC000_0017 => ERROR_NOT_ENOUGH_MEMORY,
        0xC000_001C => ERROR_INVALID_SYSTEM_SERVICE,
        0xC000_0022 => ERROR_ACCESS_DENIED,
        0xC000_0023 => ERROR_INSUFFICIENT_BUFFER,
        0xC000_0034 => ERROR_NOT_FOUND,
        0xC000_0035 => ERROR_ALREADY_EXISTS,
        0xC000_003A => ERROR_PATH_NOT_FOUND,
        0xC000_003B => ERROR_INVALID_NAME,
        0xC000_0043 => ERROR_SHARING_VIOLATION,
        0xC000_00A0 => ERROR_BUSY,
        0xC000_0102 => ERROR_TIMEOUT,
        0xC000_0120 => ERROR_CANCELLED,
        _ => {
            if nt_success(status) {
                ERROR_SUCCESS
            } else {
                ERROR_UNHANDLED_EXCEPTION
            }
        }
    }
}

