//! Win32 error codes and the NTSTATUS ↔ Win32 mapping.
//!
//! Win32 APIs report failure through `GetLastError`, which stores a
//! Win32 error code. The NT layer reports NTSTATUS values. The
//! mapping between the two is not one-to-one: several NTSTATUS values
//! collapse onto the same Win32 code, and a handful have no Win32
//! equivalent at all.

